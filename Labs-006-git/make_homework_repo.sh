#!/usr/bin/env bash
# Стартовий скрипт домашнього завдання ASG.SH.GIT.02 «Розслідування історії з трьома злиттями».
# Запуск: bash make_homework_repo.sh [--easy | --variant-b] [ЦІЛЬОВА_ПАПКА]
#   без параметра   - основний варіант (три гілки, конфлікт, навмисна неоднозначність у вимозі);
#   --easy          - спрощений варіант для повторення основи (дві гілки, без неоднозначності);
#   --variant-b     - еквівалентний варіант для повторної спроби (інший домен, та сама структура).
# Скрипт не змінює ваших глобальних налаштувань Git і не перезаписує наявну папку.
set -euo pipefail

mode="main"
case "${1:-}" in
  --easy) mode="easy"; shift ;;
  --variant-b) mode="b"; shift ;;
esac
target="${1:-homework-merges}"
if [ -e "$target" ]; then
  echo "Помилка: '$target' вже існує. Вкажіть іншу папку." >&2
  exit 1
fi
mkdir -p "$target"; cd "$target"
git init -q -b main
git config user.name "Колега ED Mentorship"
git config user.email "colleague@example.invalid"
git config core.autocrlf false
# Переносна заміна в файлі (sed без -i працює однаково в GNU і BSD/macOS).
repl() { local file="$1" expr="$2"; sed "$expr" "$file" > "$file.tmp" && mv "$file.tmp" "$file"; }
t() { export GIT_AUTHOR_DATE="2026-02-0$1T$2:00:00+02:00" GIT_COMMITTER_DATE="2026-02-0$1T$2:00:00+02:00"; }

if [ "$mode" = "b" ]; then
  item="зал"; f="rules.md"
  cat > "$f" <<'EOF'
# Правила бронювання спортивного залу

1. Одночасно в залі - не більше 12 людей.
2. Скасувати запис можна не пізніше ніж за 2 години до тренування.
3. Повторний запис на те саме тренування не створює другого місця.
4. Якщо місць немає, людина потрапляє в чергу.
EOF
  printf '# Розклад залу\n\nДемо-репозиторій домашньго завдання.\n' > README.md
else
  f="rules.md"
  cat > "$f" <<'EOF'
# Правила сервісу бронювання

1. Місткість події: не більше 25 місць.
2. Скасувати бронювання може лише його власник.
3. Повторний запит з тим самим ключем не створює друге бронювання.
4. Якщо місць немає, користувач потрапляє в лист очікування.
EOF
  printf '# Навчальний сервіс бронювання\n\nДемо-репозиторій домашньго завдання.\n' > README.md
fi
t 1 09; git add .; git commit -q -m "Початкові правила"

# typo-fix: виправлення друкарської помилки в README (є в усіх варіантах, крім easy)
if [ "$mode" != "easy" ]; then
  git switch -q -c typo-fix
  repl README.md 's/домашньго/домашнього/'
  t 1 10; git commit -q -am "Виправити друкарську помилку в README"
  git switch -q main
fi

# discounts: нове правило і зміна правила 2
git switch -q -c discounts
if [ "$mode" = "b" ]; then
  printf '5. Групою вважається запис від 4 людей; група отримує окремий тренерський слот.\n' >> "$f"
  repl "$f" 's/^2\. .*/2. Скасувати запис можна не пізніше ніж за 2 години до тренування; групи - не пізніше ніж за 24 години./'
else
  printf '5. Групою вважається бронювання від 5 осіб; група отримує знижку 10%%.\n' >> "$f"
  repl "$f" 's/^2\. .*/2. Скасувати бронювання може лише його власник; групові бронювання - не пізніше ніж за 72 години до початку./'
fi
t 2 11; git commit -q -am "Додати правила для груп"
git switch -q main

# refunds: інша зміна правила 2
git switch -q -c refunds
if [ "$mode" = "b" ]; then
  repl "$f" 's/^2\. .*/2. Скасувати запис можна не пізніше ніж за 3 години до тренування; кошти повертаються автоматично./'
else
  repl "$f" 's/^2\. .*/2. Скасувати бронювання може лише його власник не пізніше ніж за 48 годин до початку; кошти повертаються автоматично./'
fi
t 3 12; git commit -q -am "Додати правило повернення коштів"
git switch -q main

if [ "$mode" = "easy" ]; then
  cat > requirement.md <<'EOF'
# Вимога замовника до правила 2

Правило 2 має бути таким: «Скасувати бронювання може лише його власник не пізніше ніж за 48 годин до початку; групові бронювання (від 5 осіб) - не пізніше ніж за 72 години; кошти повертаються автоматично.»
EOF
elif [ "$mode" = "b" ]; then
  cat > requirement.md <<'EOF'
# Вимога адміністратора залу до правила 2

Скасування: звичайний запис - не пізніше ніж за 3 години до тренування, групи - не пізніше ніж за добу. Групою вважаємо запис на кількох людей. Кошти повертаються автоматично.
EOF
else
  cat > requirement.md <<'EOF'
# Вимога замовника до правила 2

Скасування: власник може скасувати не пізніше ніж за 48 годин до початку, групові бронювання - не пізніше ніж за 72 години. Груповим вважаємо бронювання на кількох осіб. Кошти при скасуванні повертаються автоматично.
EOF
fi
t 4 13; git add requirement.md; git commit -q -m "Додати вимогу замовника до правила 2"

echo "Готово: репозиторій '$target' (варіант: $mode). Гілки:"
git branch
